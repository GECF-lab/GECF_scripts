#!/usr/bin/env python3
# /// script
# # requires-python = ">=3.9"
# # dependencies = []
# ///
"""rename_matrix.py — remap barcode-labelled BRB-seq count matrices to sample names.

Reads the STARsolo count matrix (barcodes.tsv + features.tsv + MatrixMarket .mtx)
whose sample columns are raw barcode sequences, and remaps each barcode column to
the Sample_ID given in a two-column mapping file (Sample_ID<TAB>Barcode, optional
header).  Outputs, into --out-dir:

  barcodes.tsv              remapped sample names (column order preserved)
  features.tsv              unchanged pass-through (keeps the mtx valid)
  umiDedup-<method>.mtx     matrix data unchanged; only the barcode column remapped
  sample_barcode_map.tsv    per column: matrix label (barcode) -> Sample_ID

Behaviour:
  * UNMATCHED_<barcode>: matrix columns whose barcode is not in the mapping are
    KEPT (never silently dropped), mirroring the old pipeline's behaviour of
    preserving all STAR columns.
  * A barcode claimed by two different Sample_IDs is FATAL (exit 2): the remap
    would be ambiguous.
  * A Sample_ID mapped to more than one barcode is FATAL (exit 2): one sample
    must occupy exactly one well; name replicates with distinct Sample_IDs.
  * .mtx inputs may be symlinks (the pipeline symlinks consolidated output);
    outputs are regular files in --out-dir.
  * --exclude-prefix NAME: after remapping, DROP every column whose Sample_ID
    starts with NAME (the pipeline uses this to emit both an all-wells matrix
    — samples + empty_well_* — and a samples-only matrix from the same STAR
    output, when run with --empty-wells).  Fatal (exit 2) when the prefix
    would remove every column.

Exit codes: 0 ok, 1 bad usage, 2 mapping conflict/absence, 3 matrix file missing.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

BARCODE_RE = re.compile(r"^[ACGTN]+$")
TRIPLE_RE = re.compile(r"^(\d+)\s+(\d+)\s+([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*$")


def read_mtx(path: str):
    """Parse a MatrixMarket matrix coordinate file. Returns (rows, cols, coords)."""
    with open(path, encoding="utf-8") as fh:
        lines = [l.rstrip("\n") for l in fh]

    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if s.lower().startswith("%%matrixmarket matrix"):
            break
        i += 1
    else:
        raise ValueError(f"{path}: no '%%MatrixMarket matrix' header found")
    i += 1
    while i < len(lines) and (lines[i].strip() == "" or lines[i].strip().startswith("%")):
        i += 1
    if i >= len(lines):
        raise ValueError(f"{path}: no dimension line after MatrixMarket header")
    fmt = lines[i].split()
    if len(fmt) < 3:
        raise ValueError(f"{path}: malformed format line: {lines[i]!r}")
    rows, cols, nnz = int(fmt[0]), int(fmt[1]), int(fmt[2])
    i += 1
    coords = []
    for line in lines[i:]:
        s = line.strip()
        if not s or s.startswith("%"):
            continue
        m = TRIPLE_RE.match(s)
        if not m:
            raise ValueError(f"{path}: bad coordinate triple: {line!r}")
        r, c = int(m.group(1)) - 1, int(m.group(2)) - 1
        if not (0 <= r < rows and 0 <= c < cols):
            raise ValueError(f"{path}: coordinate out of range: {line!r} (rows={rows} cols={cols})")
        coords.append((r, c, m.group(3)))
    if len(coords) != nnz:
        raise ValueError(
            f"{path}: {len(coords)} stored values but header declares nnz={nnz}"
        )
    return rows, cols, coords


def write_mtx(path: str, rows: int, cols: int, coords) -> None:
    body = "\n".join(f"{r + 1} {c + 1} {v}" for r, c, v in coords)
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("%%MatrixMarket matrix coordinate real general\n")
        fh.write("%% generated by rename_matrix.py (barcode columns remapped to sample names)\n")
        fh.write(f"{rows} {cols} {len(coords)}\n")
        if body:
            fh.write("\n" + body + "\n")
        else:
            fh.write("\n")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-dir", required=True, help="dir with barcodes.tsv + umiDedup-*.mtx")
    p.add_argument("--mapping", required=True, help="Sample_ID<TAB>Barcode mapping (optional header)")
    p.add_argument("--out-dir", required=True, help="output dir for the remapped matrix")
    p.add_argument("--dedup-methods", default="NoDedup 1MM_Directional",
                   help="space-separated umiDedup method names to remap (default: both BRB-seq methods)")
    p.add_argument("--exclude-prefix", default=None,
                   help="after renaming, drop every column whose Sample_ID starts "
                        "with this prefix (pipeline use: emit a samples-only "
                        "matrix alongside the all-wells one when --empty-wells "
                        "is in effect, e.g. 'empty_well_')")
    args = p.parse_args(argv)

    methods = [m for m in args.dedup_methods.split() if m]
    for req in ("barcodes.tsv", "features.tsv") + tuple(f"umiDedup-{m}.mtx" for m in methods):
        if not os.path.isfile(os.path.join(args.raw_dir, req)):
            print(f"ERROR: The step that gives every sample its proper name (matching the Sample_ID from your list) is missing one of the input files it needs — the STAR counting step should have produced a file called '{req}' inside the folder {args.raw_dir}, but it is not there. This points to a problem in the earlier STAR / UMI-counting step (which is why a needed file never appeared), not in this step itself. See the messages printed above for the likely reason in the STAR step, fix that, and re-run the pipeline (using --resume-dir pointing at this same folder, so steps that already finished are not redone).",
                  file=sys.stderr)
            return 3

    # ---- read mapping --------------------------------------------------------
    bar2name: dict[str, str] = {}
    name2bars: dict[str, list[str]] = {}
    try:
        with open(args.mapping, encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
    except OSError as e:
        print(f"ERROR: Could not read the sample-to-barcode list file used to give samples their names: {args.mapping}. The specific reason reported by the system is: {e}. In plain terms: either the file is not where it is expected to be, or the computer running the pipeline does not have permission to read it. Check that the file path is correct and readable, then re-run.", file=sys.stderr)
        return 1
    if lines and lines[0].split("\t")[0].strip().lower() == "sample_id":
        lines = lines[1:]
    for ln, line in enumerate(lines, 1):
        parts = line.split("\t") if "\t" in line else line.split()
        if len(parts) != 2:
            continue
        name, barcode = parts[0].strip(), parts[1].strip().upper()
        if not name or not BARCODE_RE.fullmatch(barcode):
            continue
        prev = bar2name.get(barcode)
        if prev is not None:
            if prev != name:
                print(
                    f"ERROR: In the sample-to-barcode list (line {ln}), the barcode {barcode} is claimed by two different samples: "
                    f"'{prev}' and '{name}'. In one pooled run, a single 14-base barcode belongs to exactly one sample "
                    f"— one well on the plate — so two samples cannot both use it. The list is used to rename each column of "
                    f"the count table, so this step has to stop. Please correct the list (one sample per barcode, one well "
                    f"per sample) and re-run.",
                    file=sys.stderr,
                )
            else:
                print(
                    f"ERROR: In the sample-to-barcode list, the same sample name '{name}' appears on more than one "
                    f"different barcode (first seen earlier, again on line {ln}). One sample must occupy exactly "
                    f"one well — so it can only ever have one barcode. If this is really two different samples "
                    f"(for example a biological or technical replicate), give it its own distinct name. Otherwise "
                    f"delete the duplicated line. Then re-run.",
                    file=sys.stderr,
                )
            return 2
        bar2name[barcode] = name
        name2bars.setdefault(name, []).append(barcode)
        if len(name2bars[name]) > 1:
            print(
                f"ERROR: In the sample-to-barcode list, the sample '{name}' is linked to more than one barcode "
                f"({', '.join(name2bars[name])}), meaning it is written against more than one well. One sample "
                f"must occupy exactly one well (one barcode). If these are really separate samples (for example a "
                f"biological or technical replicate), give each of them its own distinct sample name — one well "
                f"each — and re-run.",
                file=sys.stderr,
            )
            return 2

    if not bar2name:
        print("ERROR: The sample-to-barcode list that is supposed to tell this step which name belongs to which barcode could not be turned into any usable 'name + barcode' pairs at all — every line was either missing the name, missing the barcode, or the barcode was not a valid DNA letter sequence (A/C/G/T/N). The list used was: "
              f"{args.mapping}. Check that file (it should be a two-column tab-separated list: sample name, then barcode, one sample per line) and re-run once it has at least one correct line.", file=sys.stderr)
        return 2

    # ---- remap columns ---------------------------------------------------------
    with open(os.path.join(args.raw_dir, "barcodes.tsv"), encoding="utf-8") as fh:
        bcols = [l.strip() for l in fh if l.strip()]
    if not bcols:
        print("ERROR: The list of barcodes that this step needs to rename into proper sample names (file: "
              f"{os.path.join(args.raw_dir, 'barcodes.tsv')}) is empty — meaning the earlier STAR step did not report a single barcode it found in the data. This almost always means the alignment step itself produced essentially no usable result (for example, the barcode file given to the pipeline did not match the barcodes actually present in the data at all). Check the results of the earlier alignment step and the barcode list you supplied, fix the mismatch, and re-run the pipeline (using --resume-dir pointing at this same folder, so steps that already finished are not redone).", file=sys.stderr)
        return 3

    new_cols = [bar2name.get(b, f"UNMATCHED_{b}") for b in bcols]
    seen: set[str] = set()
    ambiguous = 0
    final_cols: list[str] = []
    for name, bar in zip(new_cols, bcols):
        if name not in seen:
            seen.add(name)
            final_cols.append(name)
        else:
            final_cols.append(f"{name}__{bar}")
            ambiguous += 1
    if ambiguous:
        print(
            f"NOTE: {ambiguous} barcode column(s) in the count table corresponded to a sample name that had already "
            f"been used for an earlier column (the most common reason is that the same sample was barcoded in more "
            f"than one well, or in more than one pool batch). So each such column is kept, but with the well's "
            f"barcode added to its name (for example sampleX__ACGT...) so that no two columns collide and nothing "
            f"is silently merged. Both columns still carry all of that sample's reads from their own well. If you "
            f"want a single column per sample instead, add the two together (sum) when you analyse the results. "
            f"Column names written out: "
            + ", ".join(final_cols),
            file=sys.stderr,
        )

    matched = [b for b in bcols if b in bar2name]
    unmatched = [b for b in bcols if b not in bar2name]
    used = {bar2name[b] for b in matched}
    no_reads = [n for n in bar2name.values() if n not in used]
    if unmatched:
        print(
            f"NOTE: {len(unmatched)} of the {len(bcols)} barcode columns actually present in this pool's data were "
            f"NOT listed in your sample-to-barcode list, so they have no sample name to be given. To make sure "
            f"none of their reads are silently dropped, each is kept as its own column under a name beginning with "
            f"'UNMATCHED_' (for example UNMATCHED_ACGT...). If these belong to real samples, add them to your "
            f"sample/workbook list with their correct name and re-run so they end up properly labelled. The kept "
            f"UNMATCHED_* columns are: {', '.join(unmatched)}",
            file=sys.stderr,
        )
    if no_reads:
        print(
            f"NOTE: {len(no_reads)} mapped sample(s) have no reads in this pool (no STAR "
            f"barcode column for them) and are therefore NOT matrix columns: {', '.join(no_reads)}",
            file=sys.stderr,
        )

    # ---- exclude columns (optional: --exclude-prefix) ------------------------
    # Drop every column whose Sample_ID starts with the prefix (e.g.
    # 'empty_well_' so a samples-only matrix can be emitted alongside the
    # all-wells one from the same STAR output).
    coords_filter = None   # old-col-index -> new-col-index (None when not filtering)
    full_barcols = bcols   # original column list, for the mtx consistency check
    if args.exclude_prefix:
        n_orig = len(final_cols)
        kept_idx = [i for i, n in enumerate(final_cols) if not n.startswith(args.exclude_prefix)]
        n_dropped = n_orig - len(kept_idx)
        dropped_names = [n for i, n in enumerate(final_cols) if i not in set(kept_idx)] if n_dropped else []
        if not kept_idx:
            print(
                f"ERROR: --exclude-prefix '{args.exclude_prefix}' would remove every column of the count "
                f"table (all {n_orig} column names: {', '.join(final_cols)}), leaving an "
                f"empty matrix. Either no sample columns are present at all (check the earlier STAR/"
                f"mapping steps), or the prefix is wrong. Fix the mapping/prefix and re-run.",
                file=sys.stderr,
            )
            return 2
        if n_dropped:
            print(
                f"NOTE: --exclude-prefix '{args.exclude_prefix}' removed {n_dropped} of {n_orig} "
                f"column(s) from the output matrix (kept {len(kept_idx)}). Removed columns: "
                f"{', '.join(dropped_names)}",
                file=sys.stderr,
            )
            final_cols = [final_cols[i] for i in kept_idx]
            bcols = [bcols[i] for i in kept_idx]
            coords_filter = {old: new for new, old in enumerate(kept_idx)}

    # ---- write outputs ---------------------------------------------------------
    out = args.out_dir
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "barcodes.tsv"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(final_cols) + "\n")
    with open(os.path.join(args.raw_dir, "features.tsv"), encoding="utf-8") as src, \
         open(os.path.join(out, "features.tsv"), "w", encoding="utf-8") as dst:
        dst.write(src.read())
    with open(os.path.join(out, "sample_barcode_map.tsv"), "w", encoding="utf-8") as fh:
        for old, new in zip(bcols, final_cols):
            fh.write(f"{old}\t{new}\n")

    for mth in methods:
        rows, ncols, coords = read_mtx(os.path.join(args.raw_dir, f"umiDedup-{mth}.mtx"))
        if ncols != len(full_barcols):
            print(f"ERROR: Refusing to write out the renamed count table for the '{mth}' counting method: the count table itself has {ncols} sample columns, but the barcode list it should be renamed against lists {len(full_barcols)} — these two should always agree, and if they disagree the earlier STAR step's output is internally inconsistent. This is not a problem with your sample naming or the mapping file; it points to the STAR step's own result folder. Fix the earlier step and re-run the pipeline (using --resume-dir pointing at this same folder, so steps that already finished are not redone).",
                  file=sys.stderr)
            return 3
        out_coords = coords
        if coords_filter is not None:
            keep = set(coords_filter)
            out_coords = [(r, coords_filter[c], v) for (r, c, v) in coords if c in keep]
        write_mtx(os.path.join(out, f"umiDedup-{mth}.mtx"), rows, len(bcols), out_coords)

    print(
        f"Done remapping sample columns: out of {len(bcols)} sample(s) found in the data, {len(matched)} were recognised from your sample list and renamed properly, "
        f"{len(unmatched)} could not be matched to any entry in your list (they are kept under a name beginning with 'UNMATCHED_', so nothing is silently dropped), "
        f"and {len(methods)} finished count table(s) have been written out. "
        f"The renamed files are in: {out}",
        file=sys.stderr,
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
