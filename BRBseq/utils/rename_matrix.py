#!/usr/bin/env python3
# /// script
# # requires-python = ">=3.9"
# # dependencies = []
# ///
"""rename_matrix.py — remap barcode-labelled BRB-seq count matrices to sample names.

Reads the STARsolo count matrix (barcodes.tsv + features.tsv + MatrixMarket .mtx)
whose sample columns are raw barcode sequences, and remaps each barcode column to
the Sample_ID given in a two-column mapping file (Sample_ID<TAB>Barcode, optional
header).  Outputs, into --out-dir:

  barcodes.tsv              remapped sample names (column order preserved)
  features.tsv              unchanged pass-through (keeps the mtx valid)
  umiDedup-<method>.mtx     matrix data unchanged; only the barcode column remapped
  sample_barcode_map.tsv    per column: matrix label (barcode) -> Sample_ID

Behaviour:
  * UNMATCHED_<barcode>: matrix columns whose barcode is not in the mapping are
    KEPT (never silently dropped), mirroring the old pipeline's behaviour of
    preserving all STAR columns.
  * A barcode claimed by two different Sample_IDs is FATAL (exit 2): the remap
    would be ambiguous.
  * Duplicate barcode lines mapping to the same Sample_ID (sample barcoded in
    two wells) collapse into the one matrix column under that name; WARNING.
  * .mtx inputs may be symlinks (the pipeline symlinks consolidated output);
    outputs are regular files in --out-dir.

Exit codes: 0 ok, 1 bad usage, 2 mapping conflict/absence, 3 matrix file missing.
"""

from __future__ import annotations

import argparse
import os
import re
import sys

BARCODE_RE = re.compile(r"^[ACGTN]+$")
TRIPLE_RE = re.compile(r"^(\d+)\s+(\d+)\s+([+-]?(?:\d+\.?\d*|\.\d+)(?:[eE][+-]?\d+)?)\s*$")


def read_mtx(path: str):
    """Parse a MatrixMarket matrix coordinate file. Returns (rows, cols, coords)."""
    with open(path, encoding="utf-8") as fh:
        lines = [l.rstrip("\n") for l in fh]

    i = 0
    while i < len(lines):
        s = lines[i].strip()
        if s.lower().startswith("%%matrixmarket matrix"):
            break
        i += 1
    else:
        raise ValueError(f"{path}: no '%%MatrixMarket matrix' header found")
    i += 1
    while i < len(lines) and (lines[i].strip() == "" or lines[i].strip().startswith("%")):
        i += 1
    if i >= len(lines):
        raise ValueError(f"{path}: no dimension line after MatrixMarket header")
    fmt = lines[i].split()
    if len(fmt) < 3:
        raise ValueError(f"{path}: malformed format line: {lines[i]!r}")
    rows, cols, nnz = int(fmt[0]), int(fmt[1]), int(fmt[2])
    i += 1
    coords = []
    for line in lines[i:]:
        s = line.strip()
        if not s or s.startswith("%"):
            continue
        m = TRIPLE_RE.match(s)
        if not m:
            raise ValueError(f"{path}: bad coordinate triple: {line!r}")
        r, c = int(m.group(1)) - 1, int(m.group(2)) - 1
        if not (0 <= r < rows and 0 <= c < cols):
            raise ValueError(f"{path}: coordinate out of range: {line!r} (rows={rows} cols={cols})")
        coords.append((r, c, m.group(3)))
    if len(coords) != nnz:
        raise ValueError(
            f"{path}: {len(coords)} stored values but header declares nnz={nnz}"
        )
    return rows, cols, coords


def write_mtx(path: str, rows: int, cols: int, coords) -> None:
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("%%MatrixMarket matrix coordinate real general\n")
        fh.write("%% generated by rename_matrix.py (barcode columns remapped to sample names)\n")
        fh.write(f"{rows} {cols} {len(coords)}\n")
        fh.write("\n".join(f"{r + 1} {c + 1} {v}" for r, c, v in coords))
        fh.write("\n")


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--raw-dir", required=True, help="dir with barcodes.tsv + umiDedup-*.mtx")
    p.add_argument("--mapping", required=True, help="Sample_ID<TAB>Barcode mapping (optional header)")
    p.add_argument("--out-dir", required=True, help="output dir for the remapped matrix")
    p.add_argument("--dedup-methods", default="NoDedup 1MM_Directional",
                   help="space-separated umiDedup method names to remap (default: both BRB-seq methods)")
    p.add_argument("--no-header", action="store_true", help="mapping file has no header row")
    args = p.parse_args(argv)

    methods = [m for m in args.dedup_methods.split() if m]
    for req in ("barcodes.tsv", "features.tsv") + tuple(f"umiDedup-{m}.mtx" for m in methods):
        if not os.path.isfile(os.path.join(args.raw_dir, req)):
            print(f"ERROR: required matrix input missing: {os.path.join(args.raw_dir, req)}",
                  file=sys.stderr)
            return 3

    # ---- read mapping --------------------------------------------------------
    bar2name: dict[str, str] = {}
    dup_collapses = 0
    try:
        with open(args.mapping, encoding="utf-8", errors="replace") as fh:
            lines = fh.read().splitlines()
    except OSError as e:
        print(f"ERROR: cannot read mapping {args.mapping}: {e}", file=sys.stderr)
        return 1
    if not args.no_header and lines and lines[0].split("\t")[0].strip().lower() == "sample_id":
        lines = lines[1:]
    for ln, line in enumerate(lines, 1):
        parts = line.split("\t") if "\t" in line else line.split()
        if len(parts) != 2:
            continue
        name, barcode = parts[0].strip(), parts[1].strip().upper()
        if not name or not BARCODE_RE.fullmatch(barcode):
            continue
        prev = bar2name.get(barcode)
        if prev is not None:
            if prev != name:
                print(
                    f"ERROR: mapping conflict: barcode {barcode} is claimed by both "
                    f"'{prev}' and '{name}' (line {ln}). Two samples cannot share one "
                    "barcode in a single pool.",
                    file=sys.stderr,
                )
                return 2
            dup_collapses += 1  # same sample, second well
            continue
        bar2name[barcode] = name

    if not bar2name:
        print("ERROR: mapping produced no usable Sample_ID/Barcode pairs", file=sys.stderr)
        return 2
    if dup_collapses:
        print(
            f"WARNING: {dup_collapses} mapping line(s) reused an already-mapped barcode "
            "(sample barcoded in more than one well) — one matrix column labelled by that name.",
            file=sys.stderr,
        )

    # ---- remap columns ---------------------------------------------------------
    with open(os.path.join(args.raw_dir, "barcodes.tsv"), encoding="utf-8") as fh:
        bcols = [l.strip() for l in fh if l.strip()]
    if not bcols:
        print("ERROR: barcodes.tsv is empty", file=sys.stderr)
        return 3

    new_cols = [bar2name.get(b, f"UNMATCHED_{b}") for b in bcols]
    seen: set[str] = set()
    ambiguous = 0
    final_cols: list[str] = []
    for name, bar in zip(new_cols, bcols):
        if name not in seen:
            seen.add(name)
            final_cols.append(name)
        else:
            final_cols.append(f"{name}__{bar}")
            ambiguous += 1
    if ambiguous:
        print(
            f"WARNING: {ambiguous} column(s) resolved to an already-used Sample_ID "
            "(same sample barcoded in several distinct wells) — suffixed with the "
            "barcode to keep each well's column distinct: "
            + ", ".join(final_cols) + "\n"
            "  Both columns still carry the full sample's reads for that well. "
            "Merge them downstream (sum) if you want one column per sample.",
            file=sys.stderr,
        )

    matched = [b for b in bcols if b in bar2name]
    unmatched = [b for b in bcols if b not in bar2name]
    used = {bar2name[b] for b in matched}
    no_reads = [n for n in bar2name.values() if n not in used]
    if unmatched:
        print(
            f"WARNING: {len(unmatched)}/{len(bcols)} matrix barcode column(s) not in the mapping — "
            f"kept as UNMATCHED_*: {', '.join(unmatched)}",
            file=sys.stderr,
        )
    if no_reads:
        print(
            f"NOTE: {len(no_reads)} mapped sample(s) have no reads in this pool (no STAR "
            f"barcode column for them) and are therefore NOT matrix columns: {', '.join(no_reads)}",
            file=sys.stderr,
        )

    # ---- write outputs ---------------------------------------------------------
    out = args.out_dir
    os.makedirs(out, exist_ok=True)
    with open(os.path.join(out, "barcodes.tsv"), "w", encoding="utf-8") as fh:
        fh.write("\n".join(final_cols) + "\n")
    with open(os.path.join(args.raw_dir, "features.tsv"), encoding="utf-8") as src, \
         open(os.path.join(out, "features.tsv"), "w", encoding="utf-8") as dst:
        dst.write(src.read())
    with open(os.path.join(out, "sample_barcode_map.tsv"), "w", encoding="utf-8") as fh:
        for old, new in zip(bcols, final_cols):
            fh.write(f"{old}\t{new}\n")

    for mth in methods:
        rows, cols, coords = read_mtx(os.path.join(args.raw_dir, f"umiDedup-{mth}.mtx"))
        if cols != len(bcols):
            print(
                f"ERROR: umiDedup-{mth}.mtx has {cols} column(s) but barcodes.tsv lists "
                f"{len(bcols)} — refusing to write an inconsistent matrix.",
                file=sys.stderr,
            )
            return 3
        write_mtx(os.path.join(out, f"umiDedup-{mth}.mtx"), rows, cols, coords)

    print(
        f"rename_matrix: {len(bcols)} sample column(s): {len(matched)} remapped to sample names, "
        f"{len(unmatched)} unmatched (kept as UNMATCHED_*); {len(methods)} matrix file(s) written",
        file=sys.stderr,
    )
    print(f"rename_matrix: output -> {out}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
